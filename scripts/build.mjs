#!/usr/bin/env node
/**
 * dsh-share build.
 *
 * Produces the npm-package artifacts under lib/:
 *   lib/index.js  — host half: src/host/ bundled to plain ESM. Everything is
 *                   inlined, including the settings schema library, so the
 *                   installed package never depends on resolving
 *                   `@deepseek-ai/schemastery` from the profile at runtime
 *                   (the harness identifies a schema by its `~standard.vendor`
 *                   string, so an inlined copy is equivalent to the host's).
 *   lib/client.js — client half: src/client/ bundled to CJS, then wrapped in
 *                   the web boot handoff `window.__ModuleLoader__.load(...)`,
 *                   the closure-factory format every `dsh.client` package's
 *                   `./client` export must use (React arrives through the
 *                   injected `require`, so `react` is marked external).
 */
import { build } from 'esbuild'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(join(ROOT, 'package.json'), 'utf8'))

await mkdir(join(ROOT, 'lib'), { recursive: true })

// ---- host half: bundled TS -> ESM (zero external runtime deps) ----------------
await build({
  entryPoints: [join(ROOT, 'src', 'host', 'index.ts')],
  outfile: join(ROOT, 'lib', 'index.js'),
  format: 'esm',
  platform: 'node',
  target: 'es2022',
  bundle: true,
  sourcemap: false,
})

// ---- client half: bundled TS -> CJS, then wrap in the loader handoff -------
// `react` stays external: the browser module table answers the injected
// `require('react')`, everything else is inlined by the bundler.
await build({
  entryPoints: [join(ROOT, 'src', 'client', 'index.ts')],
  outfile: join(ROOT, 'lib', '_client.js'),
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  bundle: true,
  external: ['react'],
  sourcemap: false,
})
const clientSource = await readFile(join(ROOT, 'lib', '_client.js'), 'utf8')
await rm(join(ROOT, 'lib', '_client.js'))

const bundle = [
  '/* dsh-share client bundle — generated by scripts/build.mjs from src/client/ */',
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(pkg.name)},`,
  '  factory: (require) => {',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
  clientSource.replace(/\s+$/, '\n'),
  '    return module.exports;',
  '  },',
  '});',
  '',
].join('\n')
await writeFile(join(ROOT, 'lib', 'client.js'), bundle)

// ---- smoke checks ----
new Function(bundle) // syntax parse only; never executes (window is undefined here)
const host = await import(pathToFileURL(join(ROOT, 'lib', 'index.js')).href)
if (host.name !== 'dsh-share' || !Array.isArray(host.inject) || typeof host.apply !== 'function') {
  throw new Error('host half does not expose the expected plugin shape (name/inject/apply)')
}
if (!host.inject.includes('connection')) {
  throw new Error('host half must inject the connection service')
}

// The session-format contract is what this plugin actually couples to (it
// renders four event types out of the format-4 vocabulary, and reads the
// session store through `ctx.sessionQuery`). It is declared in `dsh.sessionFormat`
// rather than as a peerDependency because the owning package
// (`@deepseek-ai/dsh-session`) is not resolvable from a profile at runtime —
// the plugin never imports it. Assert the declaration is present so a release
// cannot ship without it.
if (!Number.isInteger(pkg.dsh?.sessionFormat)) {
  throw new Error('package.json must declare dsh.sessionFormat (the session record format this build renders)')
}

// The settings schema must survive bundling, on BOTH shapes the loader may
// pick (`exports.default ?? exports`). A missing or invalid schema is not a
// hard failure at runtime — the Plugins page simply shows no card — so it has
// to be asserted here instead.
const Config = host.Config ?? host.default?.Config
if (Config === undefined || typeof Config['~standard']?.validate !== 'function') {
  throw new Error('host half does not expose a valid settings Config schema')
}
// Validating a representative document proves the schema itself is sound:
// schemastery throws at validate time (not construction time) for a volatile
// field nested inside another volatile field, and that mistake would otherwise
// only surface as a silently missing settings card.
const sample = Config['~standard'].validate({
  host: '0.0.0.0',
  port: 3081,
  mounts: [{ name: 'apk', path: '/tmp', token: '', index: true, hidden: false }],
})
if (sample.issues !== undefined) {
  throw new Error(`settings Config rejected a valid document: ${JSON.stringify(sample.issues)}`)
}
if (sample.value.mounts?.get === undefined) {
  throw new Error('settings Config must expose `mounts` as a volatile field (a live handle with get())')
}

console.log(`built ${pkg.name}:`)
console.log('  lib/index.js  (host half, ESM, from src/host/)')
console.log('  lib/client.js (client half, __ModuleLoader__ closure bundle, from src/client/)')
